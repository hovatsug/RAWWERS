// Writes LICENCES.md: every package `npm ci` installs here, with its version
// and licence, read from the lockfile and node_modules. Dev-only tooling;
// none of it ships in an app. Run with `npm run licences` after any change
// to package.json.
import fs from 'node:fs';

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
// From the lockfile alone, so the list is the same on every machine: it
// also names the platform binaries npm installs only on their own platform.
const rows = Object.entries(lock.packages)
  .filter(([path]) => path.startsWith('node_modules/'))
  .map(([path, info]) => ({
    name: path.replace(/^.*node_modules\//, ''),
    version: info.version,
    licence: info.license ?? 'not stated in the lockfile',
    optional: info.optional ? 'only on its platform' : '',
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const direct = Object.keys(JSON.parse(fs.readFileSync('package.json', 'utf8')).devDependencies);
const lines = [
  '# Licences: tools/brand',
  '',
  'Generated by `npm run licences` from the lockfile. Dev-only: these build the',
  'brand assets on a developer machine; no app or site bundles them.',
  '',
  '| Package | Version | Licence | Pinned directly | Installed |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.licence} | ${direct.includes(r.name) ? 'yes' : ''} | ${r.optional || 'always'} |`),
  '',
  'The font outlined into the logo and icons is Archivo (SIL Open Font Licence',
  '1.1, `app/assets/fonts/OFL.txt`), which permits converting it to outlines.',
  '',
];
fs.writeFileSync('LICENCES.md', lines.join('\n'));
console.log(`LICENCES.md: ${rows.length} packages`);
